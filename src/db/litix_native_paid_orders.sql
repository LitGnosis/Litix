-- Litix Native first-party commerce, SEPARATE from Boostero and existing litix_v2_orders.
-- Apply only following isolated PostgreSQL CI, a verified production backup,
-- reviewed owner-approved pricing, and a staged production rollout.
-- DO NOT enable LITIX_NATIVE_PAID_ENABLED before production checkout safety QA.
create table if not exists public.litix_native_paid_orders (
 id uuid primary key,
 request_id uuid not null unique,
 email text not null check(length(email) between 6 and 254),
 service_id text not null check(service_id in
  ('litix-native-30day-campaign-pro')),
 brief_hash char(64) not null,
 amount_cents integer not null check(amount_cents between 300 and 20000),
 cost_budget_cents integer not null check(cost_budget_cents>=0 and cost_budget_cents<amount_cents),
 filename text not null check(length(filename) between 5 and 110),
 mime_type text not null check(mime_type in
  ('text/plain; charset=utf-8','text/html; charset=utf-8','text/csv; charset=utf-8')),
 sha256 char(64) not null,
 content text not null check(octet_length(content)<=50000),
 token_hash char(64) not null,
 payment_state text not null default 'PENDING' check(payment_state in
  ('PENDING','PROCESSING','APPROVED_UNVERIFIED','REVIEW','DECLINED','PAID','REFUNDED','CHARGEBACK')),
 delivery_state text not null default 'LOCKED' check(delivery_state in ('LOCKED','READY','REVOKED')),
 gateway_transaction_id text unique,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 check(delivery_state<>'READY' or payment_state='PAID'),
 check(gateway_transaction_id is null or length(gateway_transaction_id) between 3 and 100)
);
create index if not exists litix_native_paid_orders_state_created
 on public.litix_native_paid_orders(payment_state,created_at);
create table if not exists public.litix_native_email_outbox (
 id bigint generated by default as identity primary key,
 order_id uuid not null references public.litix_native_paid_orders(id),
 event text not null check(event in ('PAID_DELIVERY')),
 state text not null default 'PENDING' check(state in ('PENDING','SENDING','SENT','REVIEW')),
 attempted_at timestamptz,
 updated_at timestamptz not null default now(),
 unique(order_id,event)
);
comment on table public.litix_native_paid_orders is
 'First-party settled-only digital fulfillment. Not used by Boostero, Bluevine or SMM reseller charges.';
comment on table public.litix_native_email_outbox is
 'One-attempt paid delivery notifications. Unknown external email result requires owner reconciliation.';
